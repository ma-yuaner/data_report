-- 目标库：sibebid
-- 目标管理 V1：平台、GDS、部门/政策员共用一套目标模型。
-- MySQL 5.7+/8.0；不修改现有业务表，不建立跨系统外键。

CREATE TABLE IF NOT EXISTS target_metric_definition (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    metric_code VARCHAR(64) NOT NULL COMMENT '稳定指标编码',
    metric_name VARCHAR(100) NOT NULL COMMENT '指标名称',
    metric_version VARCHAR(20) NOT NULL DEFAULT 'V1' COMMENT '口径版本',
    unit_code VARCHAR(32) NOT NULL COMMENT 'SEGMENT、CNY等',
    date_basis VARCHAR(32) NOT NULL COMMENT 'ISSUE_DATE、ORDER_DATE、DEPARTURE_DATE',
    source_system VARCHAR(32) NOT NULL COMMENT 'ERP、HIVE等',
    measure_code VARCHAR(64) NOT NULL COMMENT 'ETL产出的度量编码',
    supported_scenes VARCHAR(255) NOT NULL COMMENT '逗号分隔：PLATFORM,GDS,POLICY,DEPARTMENT',
    definition TEXT NOT NULL COMMENT '正式业务定义',
    filter_description TEXT NULL COMMENT '退废、有奖、婴儿、承运航段等过滤说明',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'DRAFT、ACTIVE、DISABLED',
    effective_start DATE NULL,
    effective_end DATE NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT UNSIGNED NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_metric_version (metric_code, metric_version),
    KEY idx_target_metric_status (status, effective_start, effective_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标管理指标口径定义';

CREATE TABLE IF NOT EXISTS biz_target_plan (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '目标计划主键',
    plan_code VARCHAR(64) NOT NULL COMMENT '目标计划唯一编码',
    plan_name VARCHAR(150) NOT NULL COMMENT '目标计划名称',
    target_scene VARCHAR(32) NOT NULL COMMENT '目标场景：PLATFORM平台、GDS、POLICY政策员、DEPARTMENT部门',
    period_type VARCHAR(20) NOT NULL DEFAULT 'MONTH' COMMENT '周期类型：MONTH月、QUARTER季、YEAR年、CUSTOM自定义',
    period_start DATE NOT NULL COMMENT '目标周期开始日期',
    period_end DATE NOT NULL COMMENT '目标周期结束日期',
    progress_curve_code VARCHAR(32) NOT NULL DEFAULT 'WEEKDAY_WEIGHT' COMMENT '进度曲线编码：LINEAR线性、WEEKDAY_WEIGHT星期权重',
    progress_curve_config JSON NULL COMMENT '星期权重等进度曲线配置',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT '计划状态：DRAFT草稿、PUBLISHED已发布、ACTIVE执行中、CLOSED已关闭、VOID已作废',
    version_no INT UNSIGNED NOT NULL DEFAULT 1 COMMENT '计划版本号',
    owner_department_code VARCHAR(64) NULL COMMENT '计划归属部门编码',
    owner_department_name_snapshot VARCHAR(100) NULL COMMENT '计划归属部门名称快照',
    published_by BIGINT UNSIGNED NULL COMMENT '发布人用户ID',
    published_at DATETIME NULL COMMENT '发布时间',
    remark VARCHAR(1000) NULL COMMENT '备注',
    created_by BIGINT UNSIGNED NULL COMMENT '创建人用户ID',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_by BIGINT UNSIGNED NULL COMMENT '最后修改人用户ID',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_plan_code (plan_code),
    KEY idx_target_plan_scene_period (target_scene, period_start, period_end, status),
    KEY idx_target_plan_owner (owner_department_code, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标计划主表：保存月份、业务场景、配置状态及版本';

CREATE TABLE IF NOT EXISTS biz_target_item (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '目标明细主键',
    plan_id BIGINT UNSIGNED NOT NULL COMMENT '所属目标计划ID',
    item_code VARCHAR(80) NOT NULL COMMENT '目标明细唯一编码',
    scope_key VARCHAR(400) NOT NULL COMMENT '由业务维度生成的稳定组合键',
    metric_code VARCHAR(64) NOT NULL COMMENT '目标指标编码',
    metric_version VARCHAR(20) NOT NULL DEFAULT 'V1' COMMENT '指标口径版本',
    department_code VARCHAR(64) NOT NULL DEFAULT '' COMMENT '归属部门编码',
    department_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '归属部门名称快照',
    platform_code VARCHAR(64) NOT NULL DEFAULT '' COMMENT '平台编码',
    platform_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '平台名称快照',
    gds_code VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'GDS编码，如1A、1G、1E、1S',
    policy_group_code VARCHAR(100) NOT NULL DEFAULT '' COMMENT '政策员组合编码',
    policy_group_name_snapshot VARCHAR(150) NOT NULL DEFAULT '' COMMENT '政策员组合名称快照（兼容字段）',
    policy_leader_user_id BIGINT UNSIGNED NULL COMMENT '政策员组长用户ID',
    policy_leader_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '政策员组长姓名快照',
    policy_member_user_id BIGINT UNSIGNED NULL COMMENT '单政策员用户ID（历史兼容字段）',
    policy_member_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '单政策员姓名快照（历史兼容字段）',
    owner_user_id BIGINT UNSIGNED NULL COMMENT '责任人用户ID',
    owner_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '责任人姓名快照',
    target_value DECIMAL(20,4) NOT NULL COMMENT '目标值',
    unit_code VARCHAR(32) NOT NULL DEFAULT 'SEGMENT' COMMENT '目标单位编码，默认SEGMENT航段',
    parent_item_id BIGINT UNSIGNED NULL COMMENT '部门目标向政策员拆分时使用',
    allocation_source VARCHAR(20) NOT NULL DEFAULT 'MANUAL' COMMENT '配置来源：MANUAL手工、IMPORT导入、COPY复制',
    enabled TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用：1启用、0禁用',
    sort_order INT NOT NULL DEFAULT 0 COMMENT '显示排序号',
    remark VARCHAR(1000) NULL COMMENT '备注',
    created_by BIGINT UNSIGNED NULL COMMENT '创建人用户ID',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_by BIGINT UNSIGNED NULL COMMENT '最后修改人用户ID',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_item_code (item_code),
    UNIQUE KEY uk_target_item_scope (plan_id, metric_code, metric_version, scope_key),
    KEY idx_target_item_plan (plan_id, enabled, sort_order),
    KEY idx_target_item_platform (platform_code, plan_id),
    KEY idx_target_item_gds (gds_code, plan_id),
    KEY idx_target_item_department (department_code, plan_id),
    KEY idx_target_item_policy (policy_group_code, plan_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标明细表：保存平台、GDS、部门及政策员组合目标值';

CREATE TABLE IF NOT EXISTS biz_target_policy_member (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '政策员组合成员主键',
    plan_id BIGINT UNSIGNED NOT NULL COMMENT '所属目标计划ID',
    policy_group_code VARCHAR(100) NOT NULL COMMENT '政策员组合编码',
    member_user_id BIGINT UNSIGNED NOT NULL COMMENT '组合成员用户ID，对应花名册用户ID',
    member_name_snapshot VARCHAR(100) NOT NULL COMMENT '组合成员姓名快照',
    sort_order INT NOT NULL DEFAULT 0 COMMENT '成员显示排序号',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_policy_member (plan_id, policy_group_code, member_user_id),
    KEY idx_target_policy_member_group (plan_id, policy_group_code, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='政策员组合成员表：保存每个目标计划下政策员组合的成员名单';

CREATE TABLE IF NOT EXISTS biz_target_change_log (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '目标配置变更日志主键',
    operation_id VARCHAR(64) NOT NULL COMMENT '一次保存操作的唯一编号',
    plan_id BIGINT UNSIGNED NOT NULL COMMENT '目标计划ID',
    target_scene VARCHAR(32) NOT NULL COMMENT '目标场景：PLATFORM平台、GDS、POLICY政策员',
    action_type VARCHAR(20) NOT NULL COMMENT '操作类型：CREATE新增、UPDATE修改、PAUSE暂停、RESUME恢复',
    target_item_ids JSON NOT NULL COMMENT '本次操作涉及的目标明细ID列表',
    before_json JSON NULL COMMENT '修改前完整配置快照；新增时为空',
    after_json JSON NOT NULL COMMENT '修改后完整配置快照',
    change_reason VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '本次新增或修改原因',
    changed_by_user_id BIGINT UNSIGNED NULL COMMENT '操作人的数据中台用户ID',
    changed_by_name_snapshot VARCHAR(100) NOT NULL DEFAULT '' COMMENT '操作人名称快照',
    changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '操作时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_change_operation (operation_id),
    KEY idx_target_change_plan_time (plan_id, changed_at),
    KEY idx_target_change_scene_time (target_scene, changed_at),
    KEY idx_target_change_actor_time (changed_by_user_id, changed_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标配置通用变更日志：保存各场景配置修改前后快照及操作人';

