CREATE TABLE IF NOT EXISTS dws_target_metric_day (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    business_date DATE NOT NULL,
    metric_code VARCHAR(64) NOT NULL,
    metric_version VARCHAR(20) NOT NULL DEFAULT 'V1',
    dimension_key VARCHAR(400) NOT NULL COMMENT 'ETL生成的稳定维度组合键',
    department_code VARCHAR(64) NOT NULL DEFAULT '',
    department_name VARCHAR(100) NOT NULL DEFAULT '',
    platform_code VARCHAR(64) NOT NULL DEFAULT '',
    platform_name VARCHAR(100) NOT NULL DEFAULT '',
    gds_code VARCHAR(32) NOT NULL DEFAULT '',
    policy_group_code VARCHAR(100) NOT NULL DEFAULT '',
    policy_group_name VARCHAR(150) NOT NULL DEFAULT '',
    policy_leader_user_id BIGINT UNSIGNED NULL,
    policy_leader_name VARCHAR(100) NOT NULL DEFAULT '',
    policy_member_user_id BIGINT UNSIGNED NULL,
    policy_member_name VARCHAR(100) NOT NULL DEFAULT '',
    actual_value DECIMAL(20,4) NOT NULL DEFAULT 0,
    issue_profit DECIMAL(20,4) NULL,
    ticket_count BIGINT UNSIGNED NULL,
    data_status VARCHAR(20) NOT NULL DEFAULT 'READY' COMMENT 'READY、PARTIAL、MISSING',
    source_system VARCHAR(32) NOT NULL DEFAULT 'ERP',
    source_max_time DATETIME NULL,
    etl_batch_id VARCHAR(64) NOT NULL,
    etl_updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_metric_day (business_date, metric_code, metric_version, dimension_key),
    KEY idx_target_metric_day_period (metric_code, business_date),
    KEY idx_target_metric_day_platform (platform_code, business_date),
    KEY idx_target_metric_day_gds (gds_code, business_date),
    KEY idx_target_metric_day_department (department_code, business_date),
    KEY idx_target_metric_day_policy (policy_group_code, business_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标管理每日实际指标DWS';

CREATE TABLE IF NOT EXISTS ads_target_progress_day (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    plan_id BIGINT UNSIGNED NOT NULL,
    target_item_id BIGINT UNSIGNED NOT NULL,
    stat_date DATE NOT NULL,
    target_value_snapshot DECIMAL(20,4) NOT NULL,
    actual_today DECIMAL(20,4) NOT NULL DEFAULT 0,
    actual_cumulative DECIMAL(20,4) NOT NULL DEFAULT 0,
    planned_cumulative_rate DECIMAL(12,6) NULL COMMENT '0到1',
    completion_rate DECIMAL(12,6) NULL COMMENT '0到1，可大于1',
    progress_gap_rate DECIMAL(12,6) NULL COMMENT '完成率减正常进度',
    remaining_value DECIMAL(20,4) NOT NULL DEFAULT 0,
    required_daily_value DECIMAL(20,4) NULL,
    profit_cumulative DECIMAL(20,4) NULL,
    profit_per_segment DECIMAL(20,4) NULL,
    data_status VARCHAR(20) NOT NULL DEFAULT 'READY',
    data_through_date DATE NULL,
    etl_batch_id VARCHAR(64) NOT NULL,
    etl_updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_progress_item_day (target_item_id, stat_date),
    KEY idx_target_progress_plan_day (plan_id, stat_date),
    KEY idx_target_progress_status (data_status, stat_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标完成进度日快照';

