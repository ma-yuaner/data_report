-- 目标库：sibebid
-- 目标管理 V1：平台、GDS、部门/政策员共用一套目标模型。
-- MySQL 5.7+/8.0；不修改现有业务表，不建立跨系统外键。

CREATE TABLE IF NOT EXISTS target_metric_definition (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    metric_code VARCHAR(64) NOT NULL COMMENT '稳定指标编码',
    metric_name VARCHAR(100) NOT NULL COMMENT '指标名称',
    metric_version VARCHAR(20) NOT NULL DEFAULT 'V1' COMMENT '口径版本',
    unit_code VARCHAR(32) NOT NULL COMMENT 'SEGMENT、CNY等',
    date_basis VARCHAR(32) NOT NULL COMMENT 'ISSUE_DATE、ORDER_DATE、DEPARTURE_DATE',
    source_system VARCHAR(32) NOT NULL COMMENT 'ERP、HIVE等',
    measure_code VARCHAR(64) NOT NULL COMMENT 'ETL产出的度量编码',
    supported_scenes VARCHAR(255) NOT NULL COMMENT '逗号分隔：PLATFORM,GDS,POLICY,DEPARTMENT',
    definition TEXT NOT NULL COMMENT '正式业务定义',
    filter_description TEXT NULL COMMENT '退废、有奖、婴儿、承运航段等过滤说明',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'DRAFT、ACTIVE、DISABLED',
    effective_start DATE NULL,
    effective_end DATE NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT UNSIGNED NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_metric_version (metric_code, metric_version),
    KEY idx_target_metric_status (status, effective_start, effective_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标管理指标口径定义';

CREATE TABLE IF NOT EXISTS biz_target_plan (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    plan_code VARCHAR(64) NOT NULL COMMENT '目标计划唯一编码',
    plan_name VARCHAR(150) NOT NULL,
    target_scene VARCHAR(32) NOT NULL COMMENT 'PLATFORM、GDS、POLICY、DEPARTMENT',
    period_type VARCHAR(20) NOT NULL DEFAULT 'MONTH' COMMENT 'MONTH、QUARTER、YEAR、CUSTOM',
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    progress_curve_code VARCHAR(32) NOT NULL DEFAULT 'WEEKDAY_WEIGHT' COMMENT 'LINEAR或WEEKDAY_WEIGHT',
    progress_curve_config JSON NULL COMMENT '星期权重等进度曲线配置',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT、PUBLISHED、ACTIVE、CLOSED、VOID',
    version_no INT UNSIGNED NOT NULL DEFAULT 1,
    owner_department_code VARCHAR(64) NULL,
    owner_department_name_snapshot VARCHAR(100) NULL,
    published_by BIGINT UNSIGNED NULL,
    published_at DATETIME NULL,
    remark VARCHAR(1000) NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT UNSIGNED NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_plan_code (plan_code),
    KEY idx_target_plan_scene_period (target_scene, period_start, period_end, status),
    KEY idx_target_plan_owner (owner_department_code, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='目标计划主表';

CREATE TABLE IF NOT EXISTS biz_target_item (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    plan_id BIGINT UNSIGNED NOT NULL,
    item_code VARCHAR(80) NOT NULL COMMENT '目标明细唯一编码',
    scope_key VARCHAR(400) NOT NULL COMMENT '由业务维度生成的稳定组合键',
    metric_code VARCHAR(64) NOT NULL,
    metric_version VARCHAR(20) NOT NULL DEFAULT 'V1',
    department_code VARCHAR(64) NOT NULL DEFAULT '',
    department_name_snapshot VARCHAR(100) NOT NULL DEFAULT '',
    platform_code VARCHAR(64) NOT NULL DEFAULT '',
    platform_name_snapshot VARCHAR(100) NOT NULL DEFAULT '',
    gds_code VARCHAR(32) NOT NULL DEFAULT '',
    policy_group_code VARCHAR(100) NOT NULL DEFAULT '',
    policy_group_name_snapshot VARCHAR(150) NOT NULL DEFAULT '',
    policy_leader_user_id BIGINT UNSIGNED NULL,
    policy_leader_name_snapshot VARCHAR(100) NOT NULL DEFAULT '',
    policy_member_user_id BIGINT UNSIGNED NULL,
    policy_member_name_snapshot VARCHAR(100) NOT NULL DEFAULT '',
    owner_user_id BIGINT UNSIGNED NULL,
    owner_name_snapshot VARCHAR(100) NOT NULL DEFAULT '',
    target_value DECIMAL(20,4) NOT NULL,
    unit_code VARCHAR(32) NOT NULL DEFAULT 'SEGMENT',
    parent_item_id BIGINT UNSIGNED NULL COMMENT '部门目标向政策员拆分时使用',
    allocation_source VARCHAR(20) NOT NULL DEFAULT 'MANUAL' COMMENT 'MANUAL、IMPORT、COPY',
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    sort_order INT NOT NULL DEFAULT 0,
    remark VARCHAR(1000) NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT UNSIGNED NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_target_item_code (item_code),
    UNIQUE KEY uk_target_item_scope (plan_id, metric_code, metric_version, scope_key),
    KEY idx_target_item_plan (plan_id, enabled, sort_order),
    KEY idx_target_item_platform (platform_code, plan_id),
    KEY idx_target_item_gds (gds_code, plan_id),
    KEY idx_target_item_department (department_code, plan_id),
    KEY idx_target_item_policy (policy_group_code, plan_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='平台、GDS、部门与政策员目标明细';

